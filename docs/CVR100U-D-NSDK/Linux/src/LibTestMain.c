//注：如果调用了CVR_InitComm成功打开设备，程序结束前一定要调用CVR_CloseComm()函数，否则下次执行程序将会出错
void my_handler(int s)
{
	usleep(100000);
	printf("Caught signal %d, call CVR_CloseComm()\n",s);
	//CVR_CloseComm();
	int iRet = CVR_CloseComm();
	if(iRet != 1)
	{
		printf("CVR_CloseComm failed, Ret = %d\n", iRet);
	}
	usleep(100000);		//延时100ms 等待系统内部释放资源完成
	exit(0); 
}

